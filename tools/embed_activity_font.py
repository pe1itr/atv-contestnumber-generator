"""Embed DejaVu Sans Bold coverage masks; Pillow/FreeType are build-only.

512px source glyphs cover the largest offered Activity line without upscaling.
The C renderer area-averages these masks at the final image resolution.
"""
import json
import math
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent.parent
font = ImageFont.truetype(str(root / "assets/fonts/DejaVuSans-Bold.ttf"), 512)
chars = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ/.z?"
bounds = [font.getbbox(c, anchor="ls") for c in chars]
top = min(b[1] for b in bounds)
bottom = max(b[3] for b in bounds)
height = bottom-top
pixels = bytearray()
widths, offsets = [], []
for c, box in zip(chars, bounds):
    left = max(0, -box[0])
    width = max(math.ceil(font.getlength(c)), box[2])+left+8
    image = Image.new("L", (width, height))
    ImageDraw.Draw(image).text((4+left, -top), c, font=font, fill=255, anchor="ls")
    widths.append(width)
    offsets.append(len(pixels))
    pixels.extend(image.tobytes())

runs = bytearray()
previous, count = pixels[0], 0
for alpha in pixels:
    if alpha != previous or count == 65535:
        runs.extend((count & 255, count >> 8, previous))
        previous, count = alpha, 0
    count += 1
runs.extend((count & 255, count >> 8, previous))

target = root / "build/activity_font.h"
target.parent.mkdir(exist_ok=True)
temporary = target.with_suffix(".h.tmp")
with temporary.open("w") as out:
    out.write("/* Generated by tools/embed_activity_font.py. Do not edit. */\n")
    # External linkage retains the distribution notice in each standalone binary.
    out.write("const char activity_font_license[] =\n")
    license_text = (root / "assets/fonts/LICENSE-DejaVu.txt").read_text()
    for line in license_text.splitlines(keepends=True):
        out.write(json.dumps(line)+"\n")
    out.write(";\n")
    out.write(f"static const wchar_t activity_font_chars[] = L{json.dumps(chars)};\n")
    out.write(f"enum {{ ACTIVITY_FONT_HEIGHT={height}, ACTIVITY_FONT_SIZE={len(pixels)} }};\n")
    for name, values in (("widths", widths), ("offsets", offsets)):
        out.write(f"static const unsigned activity_font_{name}[] = {{"+",".join(map(str, values))+"};\n")
    out.write("static const unsigned char activity_font_runs[] = {\n")
    for i in range(0, len(runs), 30):
        out.write(",".join(map(str, runs[i:i+30]))+",\n")
    out.write("};\n")
temporary.replace(target)
print(f"Activity font: {len(chars)} glyphs, {height}px high, {len(runs)} embedded bytes")
